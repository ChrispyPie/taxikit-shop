-- 20261027a_dataplan_steg1.sql
-- Dataplan steg 1: faktatabellerna hålls färska automatiskt + period-API för Åkeridata (bara tillägg).
--
--   private.dp_shift_key        stabila pass-id (samma pass får samma shift_id vid varje ombyggnad)
--   private.dataplan_state      + last_check_at, last_reason, last_error, last_error_at (färskhet/fel)
--   private.dataplan_refresh    som steg 0, men behåller shift_id mellan ombyggnader
--   private.dataplan_tick       körs varje minut av pg_cron ('taxikit-dataplan-refresh'). Bygger om bara när
--                               trip_datasets('current') eller arkivet har ändrats (eller var 3:e timme).
--                               Egen transaktion, rör aldrig sessions, kan aldrig få timhämtningen att fallera.
--   private.dataplan_status     färskhet: refreshed_at, källans updated_at, stale
--   private.company_period      Åkeridata-siffror för en period (summor, pass, resor, lösa resor, serie)
--   public.get_company_period(p_token, p_from, p_to, p_detail, p_group)
--   public.get_company_shift_trips(p_token, p_ids)
-- Roller (samma som get_trip_data): ägare ser allt med namn, superadmin ser allt anonymiserat
-- (utom sin egen data), alla andra (även demo) bara sin egen data.
-- Ångra: se slutet av filen.

-- ---------- stabila pass-id ----------
create table if not exists private.dp_shift_key (
  company_id  text not null,
  forar       text not null,
  passnr      text not null,
  start_key   text not null,
  shift_id    bigint generated by default as identity unique,
  primary key (company_id, forar, passnr, start_key)
);
alter table private.dp_shift_key enable row level security;
revoke all on private.dp_shift_key from public, anon, authenticated;

insert into private.dp_shift_key (company_id, forar, passnr, start_key, shift_id)
overriding system value
select company_id, forar, passnr, start_key, shift_id from private.shift_fact
on conflict do nothing;
select setval(pg_get_serial_sequence('private.dp_shift_key', 'shift_id'),
              greatest((select coalesce(max(shift_id), 0) from private.dp_shift_key),
                       (select coalesce(max(shift_id), 0) from private.shift_fact)) + 1, false);

-- ---------- färskhet ----------
alter table private.dataplan_state
  add column if not exists last_check_at timestamptz,
  add column if not exists last_reason   text,
  add column if not exists last_error    text,
  add column if not exists last_error_at timestamptz;

-- ---------- ombyggnad (som steg 0 + stabila shift_id) ----------
create or replace function private.dataplan_refresh(p_company text default 'default')
returns jsonb language plpgsql set search_path = '' as $$
declare
  t0 timestamptz := clock_timestamp();
  v_maxlen interval;
  v_sh int; v_tr int; v_ds int; v_ms int; v_counts jsonb;
begin
  perform pg_advisory_xact_lock(hashtext('private.dataplan_refresh'), hashtext(p_company));

  delete from private.day_summary where company_id = p_company;
  delete from private.trip_fact   where company_id = p_company;
  delete from private.shift_fact  where company_id = p_company;

  -- Pass (ett åkeri idag: allt i current/arkiv hör till p_company)
  -- Stabila pass-id (steg 1): samma pass får samma shift_id vid varje ombyggnad
  insert into private.dp_shift_key (company_id, forar, passnr, start_key)
  select distinct p_company, coalesce(nullif(s.data->>'forar', ''), '710022'), coalesce(s.data->>'passnr', ''),
         left(regexp_replace(coalesce(s.data->>'start', ''), '\D', '', 'g'), 8)
    from (select data from public.shifts where dataset = 'current'
          union all
          select data from private.arkiv_shifts where dataset = 'arkiv') s
  on conflict do nothing;

  insert into private.shift_fact (shift_id, company_id, source, src_ord, forar, passnr, start_key, start_raw, slut_raw,
                                  st, en, start_app_ok, day, taxi, km, minutes, data)
  overriding system value
  select distinct on (f, pn, sk)
         (select k.shift_id from private.dp_shift_key k
           where k.company_id = p_company and k.forar = f and k.passnr = pn and k.start_key = sk),
         p_company, src, ord, f, pn, sk, data->>'start', data->>'slut',
         st, en,
         -- JS: split(' '), del 2 utan U+00A0 ska vara HH:MM
         coalesce(replace(data->>'start', chr(160), '') ~ '^\d{8} \d{2}:\d{2}(:\d{2})?$', false)
           and coalesce(replace(data->>'slut', chr(160), '') ~ '^\d{8} \d{2}:\d{2}(:\d{2})?$', false),
         st::date, coalesce(data->>'taxi', ''),
         private.dp_parse_km(data->>'km'), private.dp_parse_minutes(data->>'tid'), data
    from (
      select s.*, coalesce(nullif(s.data->>'forar', ''), '710022') f,
             coalesce(s.data->>'passnr', '') pn,
             left(regexp_replace(coalesce(s.data->>'start', ''), '\D', '', 'g'), 8) sk,
             private.shift_ts(s.data->>'start') st, private.shift_ts(s.data->>'slut') en
        from (select 'current'::text src, 0 rk, ord, data from public.shifts where dataset = 'current'
              union all
              select 'archive', 1, ord, data from private.arkiv_shifts where dataset = 'arkiv') s
    ) x
   order by f, pn, sk, rk, ord;
  get diagnostics v_sh = row_count;

  select coalesce(max(en - st), interval '0') into v_maxlen
    from private.shift_fact where company_id = p_company and en >= st;

  -- Resor
  insert into private.trip_fact (company_id, source, src_ord, forar, kvittonr, startdatum, ts, taxi, kredittyp,
                                 amount, tip, is_bom, shift_id, shift_matches, attr_day, data)
  select p_company, y.src, y.ord, y.f, y.kv, y.sd, y.ts, coalesce(y.data->>'taxi', ''), coalesce(y.data->>'kredittyp', ''),
         private.dp_parse_amount(y.data->>'belopp'), private.dp_parse_amount(y.data->>'dricks'),
         coalesce(y.data->>'kredittyp', '') = '999',
         m.shift_id, coalesce(m.n, 0),
         case when m.shift_id is not null then m.day else y.ts::date end,
         y.data
    from (
      select distinct on (f, kv, sd) *
        from (
          select t.*, coalesce(nullif(t.data->>'forar', ''), '710022') f,
                 coalesce(t.data->>'kvittonr', '') kv, coalesce(t.data->>'startdatum', '') sd,
                 case when t.data->>'startdatum' ~ '^\d{4}-\d{2}-\d{2}$'
                       and t.data->>'starttid' ~ '^\d{2}:\d{2}(:\d{2})?$'
                      then (t.data->>'startdatum' || ' ' || (t.data->>'starttid'))::timestamp end ts
            from (select 'current'::text src, 0 rk, 'current'::text ds, ord, data from public.trips where dataset = 'current'
                  union all
                  select 'archive', 1, 'arkiv', ord, data from private.arkiv_trips where dataset = 'arkiv') t
        ) x
       where not exists (select 1 from private.ersatta_kvitton e
                          where e.dataset = x.ds and e.kvittonr = x.kv and e.forar = x.f and e.startdatum = x.sd)
       order by f, kv, sd, rk, ord
    ) y
    left join lateral (
      select (array_agg(s.shift_id order by (s.source <> 'current'), s.src_ord))[1] as shift_id,
             (array_agg(s.day      order by (s.source <> 'current'), s.src_ord))[1] as day,
             count(*)::int as n
        from private.shift_fact s
       where s.company_id = p_company and s.forar = y.f
         and s.st is not null and s.en is not null
         and s.st <= y.ts and s.st >= y.ts - v_maxlen and s.en >= y.ts
      having count(*) > 0
    ) m on y.ts is not null;
  get diagnostics v_tr = row_count;

  -- Dagssummering
  insert into private.day_summary (company_id, forar, day, taxi, shifts, minutes, km, km_nan,
                                   trips, shift_trips, orphan_trips, bom_trips,
                                   kort, kredit, swish, kontant, uber_gross, faktura, ovrigt, other_kr, bom_kr, dricks)
  select p_company, forar, day, taxi,
         sum(shifts), sum(minutes), sum(km), sum(km_nan),
         sum(trips), sum(shift_trips), sum(orphan_trips), sum(bom_trips),
         sum(kort), sum(kredit), sum(swish), sum(kontant), sum(uber_gross), sum(faktura), sum(ovrigt),
         sum(other_kr), sum(bom_kr), sum(dricks)
    from (
      select forar, day, taxi, count(*) shifts, coalesce(sum(minutes), 0) minutes, coalesce(sum(km), 0) km,
             count(*) filter (where km is null) km_nan,
             0 trips, 0 shift_trips, 0 orphan_trips, 0 bom_trips,
             0 kort, 0 kredit, 0 swish, 0 kontant, 0 uber_gross, 0 faktura, 0 ovrigt, 0 other_kr, 0 bom_kr, 0 dricks
        from private.shift_fact
       where company_id = p_company and day is not null
       group by 1, 2, 3
      union all
      select forar, attr_day, taxi, 0, 0, 0, 0,
             count(*) filter (where not is_bom),
             count(*) filter (where not is_bom and shift_id is not null),
             count(*) filter (where not is_bom and shift_id is null),
             count(*) filter (where is_bom),
             coalesce(sum(amount) filter (where kredittyp = '160'), 0),
             coalesce(sum(amount) filter (where kredittyp = '283'), 0),
             coalesce(sum(amount) filter (where kredittyp = '163'), 0),
             coalesce(sum(amount) filter (where kredittyp = '1'), 0),
             coalesce(sum(amount) filter (where kredittyp = '164'), 0),
             coalesce(sum(amount) filter (where kredittyp = '161'), 0),
             coalesce(sum(amount) filter (where kredittyp = '185'), 0),
             coalesce(sum(amount) filter (where not is_bom and kredittyp not in ('160','283','163','1','164','161','185')), 0),
             coalesce(sum(amount) filter (where is_bom), 0),
             coalesce(sum(tip) filter (where not is_bom), 0)
        from private.trip_fact
       where company_id = p_company and attr_day is not null
       group by 1, 2, 3
    ) u
   group by forar, day, taxi;
  get diagnostics v_ds = row_count;

  v_ms := (extract(epoch from clock_timestamp() - t0) * 1000)::int;
  v_counts := jsonb_build_object(
    'shift_fact', v_sh, 'trip_fact', v_tr, 'day_summary', v_ds,
    'shifts_app_invalid', (select count(*) from private.shift_fact where company_id = p_company and not start_app_ok),
    'trips_multi_shift',  (select count(*) from private.trip_fact  where company_id = p_company and shift_matches > 1),
    'trips_no_time',      (select count(*) from private.trip_fact  where company_id = p_company and ts is null));

  insert into private.dataplan_state (company_id, refreshed_at, ms, counts, current_updated_at, arkiv_updated_at)
  values (p_company, now(), v_ms, v_counts,
          (select updated_at from public.trip_datasets where name = 'current'),
          (select updated_at from private.arkiv_datasets where name = 'arkiv'))
  on conflict (company_id) do update
     set refreshed_at = excluded.refreshed_at, ms = excluded.ms, counts = excluded.counts,
         current_updated_at = excluded.current_updated_at, arkiv_updated_at = excluded.arkiv_updated_at;

  return v_counts || jsonb_build_object('ms', v_ms);
end $$;

revoke all on function private.dataplan_refresh(text) from public, anon, authenticated;

-- ---------- automatisk uppdatering ----------
create or replace function private.dataplan_tick(p_company text default 'default')
returns text language plpgsql set search_path = '' as $$
declare
  v_cur timestamptz; v_ark timestamptz; v_why text; v_res jsonb;
  st private.dataplan_state;
begin
  perform set_config('lock_timeout', '5s', true);
  -- Bara en uppdatering åt gången; är en igång hoppar vi över denna minut.
  if not pg_try_advisory_xact_lock(hashtext('private.dataplan_refresh'), hashtext(p_company)) then
    return 'busy';
  end if;
  -- Källornas stämplar läses FÖRE ombyggnaden: ändras källan under tiden byggs det om nästa minut.
  select updated_at into v_cur from public.trip_datasets where name = 'current';
  select updated_at into v_ark from private.arkiv_datasets where name = 'arkiv';
  select * into st from private.dataplan_state where company_id = p_company;
  v_why := case
    when st.company_id is null                         then 'first'
    when v_cur is distinct from st.current_updated_at  then 'current'
    when v_ark is distinct from st.arkiv_updated_at    then 'arkiv'
    when st.refreshed_at < now() - interval '3 hours'  then 'periodic'
  end;
  if v_why is null then
    return 'fresh';
  end if;
  if st.last_error_at > now() - interval '10 minutes' then
    return 'backoff';
  end if;
  begin
    v_res := private.dataplan_refresh(p_company);
    update private.dataplan_state
       set current_updated_at = v_cur, arkiv_updated_at = v_ark, last_check_at = now(),
           last_reason = v_why, last_error = null, last_error_at = null
     where company_id = p_company;
    return 'refreshed ' || v_why || ' ' || coalesce(v_res->>'ms', '?') || ' ms';
  exception when others then
    -- ombyggnaden rullas tillbaka; gamla siffror ligger kvar
    insert into private.dataplan_state (company_id, refreshed_at, ms, counts, last_error, last_error_at, last_reason)
    values (p_company, 'epoch', 0, '{}', left(sqlerrm, 500), now(), v_why)
    on conflict (company_id) do update
       set last_error = excluded.last_error, last_error_at = excluded.last_error_at,
           last_reason = excluded.last_reason, last_check_at = now();
    return 'error: ' || left(sqlerrm, 200);
  end;
end $$;
revoke all on function private.dataplan_tick(text) from public, anon, authenticated;

create or replace function private.dataplan_status(p_company text default 'default')
returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'refreshed_at', s.refreshed_at,
    'source_updated_at', c.updated_at,
    'stale', s.company_id is null or c.updated_at is distinct from s.current_updated_at
             or (select updated_at from private.arkiv_datasets where name = 'arkiv') is distinct from s.arkiv_updated_at,
    'last_error_at', s.last_error_at)
    from (select 1) one
    left join private.dataplan_state s on s.company_id = p_company
    left join public.trip_datasets c on c.name = 'current'
$$;
revoke all on function private.dataplan_status(text) from public, anon, authenticated;

-- ---------- periodsiffror ----------
-- p_scope: 'all' (ägare), 'anon' (superadmin: andras förar-id byts mot 'p'||shift_id / 'n'||löpnr), 'own' (bara p_driver)
create or replace function private.company_period(p_company text, p_from date, p_to date, p_scope text,
                                                  p_driver text, p_detail boolean, p_group text default null)
returns jsonb language plpgsql stable set search_path = '' as $$
declare
  v_tot jsonb; v_shifts jsonb; v_loose jsonb; v_series jsonb; v_cnt jsonb;
begin
  if p_scope not in ('all', 'anon', 'own') then
    raise exception 'bad_scope' using errcode = '22023';
  end if;

  select jsonb_build_object(
           'antal', coalesce(sum(d.trips), 0), 'shifts', coalesce(sum(d.shifts), 0),
           'minutes', coalesce(sum(d.minutes), 0), 'km', coalesce(sum(d.km), 0), 'km_nan', coalesce(sum(d.km_nan), 0),
           'kort', coalesce(sum(d.kort), 0), 'kredit', coalesce(sum(d.kredit), 0), 'swish', coalesce(sum(d.swish), 0),
           'kontant', coalesce(sum(d.kontant), 0), 'uber', coalesce(sum(d.uber_gross), 0),
           'faktura', coalesce(sum(d.faktura), 0), 'ovrigt', coalesce(sum(d.ovrigt), 0),
           'bom', coalesce(sum(d.bom_kr), 0), 'bom_trips', coalesce(sum(d.bom_trips), 0),
           'dricks', coalesce(sum(d.dricks), 0), 'inkort', coalesce(sum(d.inkort), 0),
           'loose_trips', coalesce(sum(d.orphan_trips), 0))
    into v_tot
    from private.day_summary d
   where d.company_id = p_company and d.day between p_from and p_to
     and (p_scope <> 'own' or d.forar = p_driver);

  with sh as (
    select s.shift_id, s.source, s.src_ord, s.forar, s.passnr, s.start_raw, s.slut_raw, s.taxi, s.data,
           case when p_scope = 'anon' and s.forar is distinct from p_driver then 'p' || s.shift_id else s.forar end fv
      from private.shift_fact s
     where s.company_id = p_company and s.day between p_from and p_to
       and (p_scope <> 'own' or s.forar = p_driver)
  ), tr as (
    select t.shift_id, t.source, t.src_ord, t.data, t.amount, t.kredittyp, t.is_bom
      from private.trip_fact t
     where t.company_id = p_company and t.shift_id in (select shift_id from sh)
  ), agg as (
    select tr.shift_id, count(*) n,
           coalesce(sum(tr.amount) filter (where not tr.is_bom and tr.kredittyp <> '164'), 0)
         + coalesce(sum(tr.amount) filter (where tr.kredittyp = '164'), 0) * (1 - 0.26) inkort,
           case when p_detail then jsonb_agg(
             jsonb_strip_nulls(jsonb_build_object(
               'kvittonr', tr.data->'kvittonr', 'startdatum', tr.data->'startdatum', 'starttid', tr.data->'starttid',
               'sluttid', tr.data->'sluttid', 'startzon', tr.data->'startzon', 'slutzon', tr.data->'slutzon',
               'belopp', tr.data->'belopp', 'kredittyp', tr.data->'kredittyp', 'dricks', tr.data->'dricks'))
             order by (tr.source <> 'current'), tr.src_ord) end trips
      from tr group by tr.shift_id
  )
  select coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
           'id', sh.shift_id, 'passnr', sh.passnr, 'forar', sh.fv, 'start', sh.start_raw, 'slut', sh.slut_raw,
           'taxi', sh.taxi, 'n', coalesce(agg.n, 0), 'inkort', coalesce(agg.inkort, 0),
           'trips', case when p_detail then coalesce(agg.trips, '[]'::jsonb) end))
           order by sh.start_raw desc, (sh.source <> 'current'), sh.src_ord), '[]'::jsonb),
         jsonb_build_object(
           'forare', case when p_scope = 'all' then count(distinct sh.forar) end,
           'bilar', count(distinct nullif(sh.taxi, '')))
    into v_shifts, v_cnt
    from sh left join agg on agg.shift_id = sh.shift_id;

  select coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
           'kvittonr', t.data->'kvittonr',
           'forar', case when p_scope = 'anon' and t.forar is distinct from p_driver then 'n' || t.rn else t.forar end,
           'startdatum', t.data->'startdatum', 'starttid', t.data->'starttid',
           'sluttid', t.data->'sluttid', 'startzon', t.data->'startzon', 'slutzon', t.data->'slutzon',
           'belopp', t.data->'belopp', 'kredittyp', t.data->'kredittyp', 'dricks', t.data->'dricks'))
           order by t.rn), '[]'::jsonb)
    into v_loose
    from (select x.*, row_number() over (order by (x.source <> 'current'), x.src_ord) rn
            from private.trip_fact x
           where x.company_id = p_company and x.shift_id is null and x.attr_day between p_from and p_to
             and (p_scope <> 'own' or x.forar = p_driver)) t;

  if p_group in ('day', 'month') then
    select coalesce(jsonb_agg(jsonb_build_object('key', k, 'antal', antal, 'shifts', shifts, 'minutes', minutes,
                                                 'km', km, 'inkort', inkort) order by k), '[]'::jsonb)
      into v_series
      from (select case when p_group = 'day' then to_char(d.day, 'YYYY-MM-DD') else to_char(d.day, 'YYYY-MM') end k,
                   sum(d.trips) antal, sum(d.shifts) shifts, sum(d.minutes) minutes, sum(d.km) km, sum(d.inkort) inkort
              from private.day_summary d
             where d.company_id = p_company and d.day between p_from and p_to
               and (p_scope <> 'own' or d.forar = p_driver)
             group by 1) z;
  end if;

  return jsonb_build_object(
    'from', p_from, 'to', p_to, 'scope', p_scope, 'detail', p_detail,
    'totals', v_tot, 'forare', v_cnt->'forare', 'bilar', v_cnt->'bilar',
    'shifts', v_shifts, 'loose', v_loose, 'series', v_series,
    'last_updated', (select meta->'last_updated' from public.trip_datasets where name = 'current'),
    'fresh', private.dataplan_status(p_company));
end $$;
revoke all on function private.company_period(text, date, date, text, text, boolean, text) from public, anon, authenticated;

create or replace function public.get_company_period(p_token text, p_from date, p_to date,
                                                     p_detail boolean default true, p_group text default null)
returns json language plpgsql security definer
set search_path = 'pg_catalog', 'public' set work_mem = '32MB' as $$
declare a record; v_cat text; v_scope text;
begin
  select * into a from private.session_actor(p_token);
  if p_from is null or p_to is null or p_to < p_from or p_from < date '2000-01-01' or p_to > date '2100-12-31'
     or p_to - p_from > 400 then
    raise exception 'bad_range' using errcode = '22023';
  end if;
  if p_group is not null and p_group not in ('day', 'month') then
    raise exception 'bad_group' using errcode = '22023';
  end if;
  v_cat := coalesce(a.category, '');
  v_scope := case when v_cat = 'agare' then 'all'
                  when v_cat = any (private.company_view_roles()) then 'anon'
                  else 'own' end;
  -- Resorna skickas med direkt bara för korta perioder (≤ 62 dagar); annars hämtas de per pass.
  return private.company_period('default', p_from, p_to, v_scope, a.driver_id,
                                coalesce(p_detail, true) and p_to - p_from <= 62, p_group)::json;
end $$;
revoke all on function public.get_company_period(text, date, date, boolean, text) from public;
grant execute on function public.get_company_period(text, date, date, boolean, text) to anon, authenticated;

create or replace function public.get_company_shift_trips(p_token text, p_ids bigint[])
returns json language plpgsql security definer
set search_path = 'pg_catalog', 'public' as $$
declare a record; v_cat text; v_scope text; r jsonb;
begin
  select * into a from private.session_actor(p_token);
  if p_ids is null or cardinality(p_ids) > 300 then
    raise exception 'bad_ids' using errcode = '22023';
  end if;
  v_cat := coalesce(a.category, '');
  v_scope := case when v_cat = 'agare' then 'all'
                  when v_cat = any (private.company_view_roles()) then 'anon'
                  else 'own' end;
  select coalesce(jsonb_object_agg(z.shift_id::text, z.trips), '{}'::jsonb) into r
    from (select t.shift_id, jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
                   'kvittonr', t.data->'kvittonr', 'startdatum', t.data->'startdatum', 'starttid', t.data->'starttid',
                   'sluttid', t.data->'sluttid', 'startzon', t.data->'startzon', 'slutzon', t.data->'slutzon',
                   'belopp', t.data->'belopp', 'kredittyp', t.data->'kredittyp', 'dricks', t.data->'dricks'))
                   order by (t.source <> 'current'), t.src_ord) trips
            from private.trip_fact t
           where t.company_id = 'default' and t.shift_id = any (p_ids)
             and (v_scope <> 'own' or t.forar = a.driver_id)
           group by t.shift_id) z;
  return r::json;
