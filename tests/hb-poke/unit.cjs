assert.doesNotMatch(bot, /if \(!sticky\) state\.hideT = setTimeout\(hideBubble, BUBBLE_MS\)/);
assert.match(bot, /function poke\(/);
assert.match(bot, /el\.btn\.addEventListener\('click'/);
assert.match(bot, /poke\(\);/);
