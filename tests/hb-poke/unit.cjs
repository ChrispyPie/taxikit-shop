assert.doesNotMatch(bot, /className = 'hb-panel'/);
assert.match(bot, /Hjälp finns under frågetecknet/);
assert.match(sc, /id: 'ankomster-sen'/);
assert.match(sc, /id: 'inkorg-olast'/);
assert.match(sc, /id: 'kordata-manga'/);
assert.match(sc, /id: 'ankomster-installt'/);
